import Foundation
import PvPCore

// Writes a battle report for a recorded battle: ManGo's settings, a timeline of what the
// screen reader saw and did, and each opponent charged move with the energy math, ManGo's
// fast move count and the count from watching the recording.
//
//   swift run battle-report <reads.json> <resources dir> <hand-counts.json> <fixture name>

let a = CommandLine.arguments
guard a.count == 5 else {
    print("usage: battle-report <reads.json> <resources dir> <hand-counts.json> <fixture name>")
    exit(1)
}
let res = URL(fileURLWithPath: a[2])
let data = try GameData(
    gamemasterJSON: Data(contentsOf: res.appending(path: "gamemaster.json")),
    rankingsJSON: Data(contentsOf: res.appending(path: "rankings-1500.json")))
let reads = try JSONDecoder().decode([ScreenRead].self, from: Data(contentsOf: URL(fileURLWithPath: a[1])))

struct HandCounts: Decodable {
    let video: String
    let description: String
    let counts: [Int?]
    let notes: [String: String]?
    let countTargets: [Target]?
    let energyCheckpoints: [Checkpoint]?
    let throwEnergy: [ThrowEnergy]?
    let observedFastMoves: [String: String]?
    struct Target: Decodable { let speciesId: String; let moveId: String }
    struct Checkpoint: Decodable { let time: Double; let speciesId: String; let energy: Int }
    struct ThrowEnergy: Decodable {
        let ordinal: Int; let speciesId: String; let moveId: String; let exact: Int?; let minimum: Int?
    }
}
let hand = try JSONDecoder().decode([String: HandCounts].self, from: Data(contentsOf: URL(fileURLWithPath: a[3])))[a[4]]

func clock(_ t: TimeInterval) -> String { String(format: "%d:%05.2f", Int(t) / 60, t.truncatingRemainder(dividingBy: 60)) }
func name(_ id: String?) -> String { id.flatMap { data.species[$0]?.speciesName } ?? "?" }

var automation = BattleAutomation(data: data)
// Trying other timing: e.g. STOP_LEAD=0.05 RESUME_LEAD=0.1 battle-report …
let env = ProcessInfo.processInfo.environment
if let v = env["STOP_LEAD"].flatMap(Double.init) { automation.stopLead = v }
if let v = env["RESUME_LEAD"].flatMap(Double.init) { automation.resumeLead = v }
if let v = env["FAINT_RESUME_LEAD"].flatMap(Double.init) { automation.faintResumeLead = v }
if let v = env["PLAYER_FREEZE_BEFORE_CUE"].flatMap(Double.init) { automation.playerFreezeBeforeCue = v }
if let v = env["GO_DELAY"].flatMap(Double.init) { automation.goDelay = v }
if let off = env["RULES_OFF"] { Rules.disabled = Set(off.split(separator: ",").map(String.init)) }
if env["HIT_TEXT"] == "0" { automation.useFirstHitText = false }
if env["HIT_COUNT"] == "1" { automation.useHitCount = true }
var tracker = OpponentTracker(data: data)
var timeline: [String] = []
var throwsSeen: [BattleAutomation.ChargedMoveObservation] = []
var wasPaused = false
var evidenceFailures: [String] = []
let checkpoints = hand?.energyCheckpoints ?? []
var checkedPoints = Set<Int>()
for read in reads {
    automation.process(read, tracker: &tracker)
    let snap = tracker.snapshot(at: read.time)
    timeline += automation.logThisRead.map { "\(clock(read.time))  \($0)" }
    throwsSeen += automation.throwsThisRead
    for (i, point) in checkpoints.enumerated() where !checkedPoints.contains(i) && read.time >= point.time {
        checkedPoints.insert(i)
        if read.time - point.time >= 0.5 || snap.pokemon?.speciesId != point.speciesId || snap.energy != point.energy {
            evidenceFailures.append("At \(point.time)s expected \(point.speciesId) energy \(point.energy); observed \(snap.pokemon?.speciesId ?? "unknown") energy \(snap.energy) at \(read.time)s")
        }
    }
    if tracker.isPaused != wasPaused, let p = snap.pokemon {
        timeline.append("\(clock(read.time))    \(tracker.isPaused ? "stopped" : "running")  \(name(p.speciesId)) at \(snap.energy)")
        wasPaused = tracker.isPaused
    }
}

var out: [String] = []
out.append("ManGo battle report")
out.append(String(repeating: "=", count: 72))
if let hand {
    out.append("Video:        \(hand.video)")
    out.append("Battle:       \(hand.description)")
}
out.append("Screen text:  PvPCore/Tests/PvPCoreTests/Fixtures/\(a[4]).json (original observation timestamps)")
out.append("Generated by: PvPCore/Sources/battle-report (swift run battle-report …)")
out.append("")
out.append("HOW MANGO COUNTS")
out.append("  Energy = fast moves × the fast move's energy, minus charged moves thrown (max 100).")
out.append("  Turns are 0.5s. The opponent is assumed to throw PvPoke's recommended fast move nonstop.")
out.append("  - The clock stops when your charged move buttons vanish (either side's charged move, a")
out.append("    faint) and restarts when they're back. Stops/restarts are back-dated (settings below)")
out.append("    to estimate when the UI changed between reads; actual read intervals vary.")
out.append("  - Your charged move waits for your fast move to finish; the battle runs on until then.")
out.append("  - When you throw, they get their finished fast moves plus the one in progress, including")
out.append("    when your moves line up (they start one on the turn your charged move takes).")
out.append("    Not when they throw on the same turn (their charged move in the same stop as yours).")
out.append("  - When they throw, only finished fast moves count; then they start fresh.")
out.append("  - A switch takes 1 turn. 0 for a fainted Pokémon's replacement, straight after their")
out.append("    charged move, or after anyone's charged move when the switch shows as the battle")
out.append("    restarts. After your Pokémon faints, their switch (theirs still in) costs a turn.")
out.append("  - Benched Pokémon keep their energy.")
out.append("")
out.append("SETTINGS (heuristic timing; not proof of accuracy)")
out.append(String(format: "  The battle starts %.3fs after \"GO\" is first read.", automation.goDelay))
out.append(String(format: "  Battle stops %.3fs before your buttons are first read as gone.", automation.stopLead))
out.append(String(format: "  Your charged move freezes the battle %.3fs before \"Get Ready!\" is read.", automation.playerFreezeBeforeCue))
out.append(String(format: "  Battle resumes %.3fs before your buttons are read again (%.3fs after a faint).", automation.resumeLead, automation.faintResumeLead))
out.append("")
out.append("OPPONENT FAST MOVES ASSUMED (PvPoke recommended)")
for p in tracker.team {
    if let f = p.fastMove {
        out.append("  \(name(p.speciesId).padding(toLength: 22, withPad: " ", startingAt: 0)) \(f.name): +\(f.energyGain) energy every \(f.turns) turn\(f.turns == 1 ? "" : "s") (\(String(format: "%.1f", Double(f.turns) * 0.5))s)")
    }
}
out.append("")
out.append("OPPONENT CHARGED MOVES")
out.append("  #  time     Pokémon               move (cost)               energy        fast moves  hand  match")
var lastAfter: [String: Int] = [:]
var matches = 0, checked = 0
for (i, t) in throwsSeen.enumerated() {
    let prev = lastAfter[t.speciesId] ?? 0
    let gain = t.fastMove?.energyGain ?? 0
    let count = t.fastMoveCount ?? 0
    lastAfter[t.speciesId] = t.energyAfter
    let handCount = hand.flatMap { i < $0.counts.count ? $0.counts[i] : nil }
    var verdict = "  -"
    if let h = handCount {
        if let targets = hand?.countTargets, i < targets.count {
            let target = targets[i]
            if t.speciesId != target.speciesId || t.move.moveId != target.moveId {
                evidenceFailures.append("Throw \(i + 1): expected \(target.speciesId) \(target.moveId), observed \(t.speciesId) \(t.move.moveId)")
            }
        } else { evidenceFailures.append("Throw \(i + 1): missing label identity") }
        checked += 1
        if h == count { matches += 1; verdict = "  ✓" } else { verdict = "  ✗ (\(count > h ? "+" : "")\(count - h))" }
    }
    let move = "\(t.move.name) (\(t.move.energy))".padding(toLength: 25, withPad: " ", startingAt: 0)
    let energy = "\(t.energyBefore) → \(t.energyAfter)".padding(toLength: 13, withPad: " ", startingAt: 0)
    out.append(String(format: "  %-2d %@  %@ %@ %@ %-11d %@%@",
                      i + 1, clock(t.time), name(t.speciesId).padding(toLength: 21, withPad: " ", startingAt: 0),
                      move, energy, count, (handCount.map { String($0) } ?? "?").padding(toLength: 4, withPad: " ", startingAt: 0), verdict))
    out.append("       calc: \(t.energyBefore) = \(prev) left before + \(count) × \(gain) (\(t.fastMove?.name ?? "?"))\(t.energyBefore - prev - count * gain != 0 ? " + \(t.energyBefore - prev - count * gain) (cap/corrections)" : ""); after: \(t.energyBefore) − \(t.move.energy) = \(t.energyAfter)")
    if let note = hand?.notes?[String(i + 1)] { out.append("       note: \(note)") }
}
out.append("")
out.append("SUMMARY")
out.append("  \(matches) of \(checked) hand-counted charged moves match ManGo's fast move count exactly.")
out.append("  \(throwsSeen.filter { $0.energyBefore < $0.move.energy }.count) thrown with less energy than they cost (by ManGo's count).")
if throwsSeen.count > checked { out.append("  \(throwsSeen.count - checked) not hand-counted.") }
out.append("")
out.append("TIMELINE (what the screen reader saw and did)")
out.append(contentsOf: timeline.map { "  " + $0 })
for (i, point) in checkpoints.enumerated() where !checkedPoints.contains(i) {
    evidenceFailures.append("Missing energy checkpoint at \(point.time)s")
}
for point in hand?.throwEnergy ?? [] {
    let i = point.ordinal - 1
    guard throwsSeen.indices.contains(i) else {
        evidenceFailures.append("Missing energy-labelled throw \(point.ordinal)")
        continue
    }
    let observed = throwsSeen[i]
    if observed.speciesId != point.speciesId || observed.move.moveId != point.moveId {
        evidenceFailures.append("Wrong identity at energy-labelled throw \(point.ordinal)")
    }
    if let exact = point.exact, observed.energyBefore != exact {
        evidenceFailures.append("Throw \(point.ordinal): expected exactly \(exact), estimated \(observed.energyBefore)")
    }
    if let minimum = point.minimum, observed.energyBefore < minimum {
        evidenceFailures.append("Throw \(point.ordinal): expected at least \(minimum), estimated \(observed.energyBefore)")
    }
}
for (species, move) in (hand?.observedFastMoves ?? [:]).sorted(by: { $0.key < $1.key }) {
    if throwsSeen.first(where: { $0.speciesId == species })?.fastMove?.moveId != move {
        evidenceFailures.append("\(species): assumed fast move differs from observed \(move)")
    }
}
let missingCounts = hand.map { $0.counts.dropFirst(throwsSeen.count).compactMap { $0 }.count } ?? 0
let underfunded = throwsSeen.filter { $0.energyBefore < $0.move.energy }.count
let valid = !throwsSeen.isEmpty && matches == checked && missingCounts == 0 && underfunded == 0 && evidenceFailures.isEmpty
out.append("")
out.append("VALIDATION: \(valid ? "PASS (available evidence only)" : "FAIL")")
out.append("  \(missingCounts) labelled throws missing; \(checked - matches) count mismatches; \(underfunded) underfunded throws.")
if throwsSeen.isEmpty { out.append("  No charged moves detected.") }
out.append(contentsOf: evidenceFailures.map { "  " + $0 })
print(out.joined(separator: "\n"))
if !valid { exit(1) }
