import Foundation
import PvPCore

// Writes a battle report for a recorded battle: ManGo's settings, a timeline of what the
// screen reader saw and did, and each opponent charged move with the energy math, ManGo's
// fast move count and the count from watching the recording.
//
//   swift run battle-report <reads.json> <resources dir> <hand-counts.json> <fixture name>

let a = CommandLine.arguments
guard a.count == 5 else {
    print("usage: battle-report <reads.json> <resources dir> <hand-counts.json> <fixture name>")
    exit(1)
}
let res = URL(fileURLWithPath: a[2])
let data = try GameData(
    gamemasterJSON: Data(contentsOf: res.appending(path: "gamemaster.json")),
    rankingsJSON: Data(contentsOf: res.appending(path: "rankings-1500.json")), topRanked: 500)
let reads = try JSONDecoder().decode([ScreenRead].self, from: Data(contentsOf: URL(fileURLWithPath: a[1])))

struct HandCounts: Decodable {
    let video: String
    let description: String
    let counts: [Int?]
    let notes: [String: String]?
}
let hand = try JSONDecoder().decode([String: HandCounts].self, from: Data(contentsOf: URL(fileURLWithPath: a[3])))[a[4]]

func clock(_ t: TimeInterval) -> String { String(format: "%d:%05.2f", Int(t) / 60, t.truncatingRemainder(dividingBy: 60)) }
func name(_ id: String?) -> String { id.flatMap { data.species[$0]?.speciesName } ?? "?" }

var automation = BattleAutomation(data: data)
var tracker = OpponentTracker(data: data)
var timeline: [String] = []
struct Throw { let time: TimeInterval; let speciesId: String; let move: Move; let fast: Move?; let before: Int; let after: Int }
var throwsSeen: [Throw] = []
var logCount = 0
var wasPaused = false
for read in reads {
    automation.process(read, tracker: &tracker)
    let snap = tracker.snapshot(at: read.time)
    for line in automation.log.dropFirst(min(logCount, automation.log.count)) {
        timeline.append("\(clock(read.time))  \(line)")
        // Energy from the log line itself ("(48 → 8)"): it includes corrections made at the throw.
        if line.contains(" used "), let p = tracker.active, let move = p.revealedChargedMoves.last,
           let open = line.range(of: "(", options: .backwards),
           let arrow = line.range(of: " → ", range: open.upperBound..<line.endIndex),
           let close = line.range(of: ")", range: arrow.upperBound..<line.endIndex),
           let b = Int(line[open.upperBound..<arrow.lowerBound]), let e = Int(line[arrow.upperBound..<close.lowerBound]) {
            throwsSeen.append(Throw(time: read.time, speciesId: p.speciesId, move: move, fast: p.fastMove, before: b, after: e))
        }
    }
    logCount = automation.log.count
    if tracker.isPaused != wasPaused, let p = snap.pokemon {
        timeline.append("\(clock(read.time))    \(tracker.isPaused ? "stopped" : "running")  \(name(p.speciesId)) at \(snap.energy)")
        wasPaused = tracker.isPaused
    }
}

var out: [String] = []
out.append("ManGo battle report")
out.append(String(repeating: "=", count: 72))
if let hand {
    out.append("Video:        \(hand.video)")
    out.append("Battle:       \(hand.description)")
}
out.append("Screen text:  PvPCore/Tests/PvPCoreTests/Fixtures/\(a[4]).json (read every 0.25s)")
out.append("Generated by: PvPCore/Sources/battle-report (swift run battle-report …)")
out.append("")
out.append("HOW MANGO COUNTS")
out.append("  Energy = fast moves × the fast move's energy, minus charged moves thrown (max 100).")
out.append("  Turns are 0.5s. The opponent is assumed to throw PvPoke's recommended fast move nonstop.")
out.append("  - The clock stops when your charged move buttons vanish (either side's charged move, a")
out.append("    faint) and restarts when they're back. Stops/restarts are back-dated (settings below)")
out.append("    because the screen is read 4 times a second and changed up to 0.25s earlier.")
out.append("  - Your charged move waits for your fast move to finish; the battle runs on until then.")
out.append("  - When you throw, they get their finished fast moves plus the one in progress, including")
out.append("    when your moves line up (they start one on the turn your charged move takes).")
out.append("  - When they throw, only finished fast moves count; then they start fresh.")
out.append("  - A switch takes 1 turn; 0 after a faint or straight after their charged move.")
out.append("  - Benched Pokémon keep their energy.")
out.append("")
out.append("SETTINGS (fitted on the hand counts of all recorded battles)")
out.append(String(format: "  Battle stops %.3fs before your buttons are first read as gone.", automation.stopLead))
out.append(String(format: "  Your charged move freezes the battle %.3fs before \"Get Ready!\" is read.", automation.playerFreezeBeforeCue))
out.append(String(format: "  Battle resumes %.3fs before your buttons are read again (%.3fs after a faint).", automation.resumeLead, automation.faintResumeLead))
out.append("")
out.append("OPPONENT FAST MOVES ASSUMED (PvPoke recommended)")
for p in tracker.team {
    if let f = p.fastMove {
        out.append("  \(name(p.speciesId).padding(toLength: 22, withPad: " ", startingAt: 0)) \(f.name): +\(f.energyGain) energy every \(f.turns) turn\(f.turns == 1 ? "" : "s") (\(String(format: "%.1f", Double(f.turns) * 0.5))s)")
    }
}
out.append("")
out.append("OPPONENT CHARGED MOVES")
out.append("  #  time     Pokémon               move (cost)               energy        fast moves  hand  match")
var lastAfter: [String: Int] = [:]
var matches = 0, checked = 0
for (i, t) in throwsSeen.enumerated() {
    let prev = lastAfter[t.speciesId] ?? 0
    let gain = t.fast?.energyGain ?? 0
    let count = gain > 0 ? (t.before - prev) / gain : 0
    lastAfter[t.speciesId] = t.after
    let handCount = hand.flatMap { i < $0.counts.count ? $0.counts[i] : nil }
    var verdict = "  -"
    if let h = handCount {
        checked += 1
        if h == count { matches += 1; verdict = "  ✓" } else { verdict = "  ✗ (\(count > h ? "+" : "")\(count - h))" }
    }
    let move = "\(t.move.name) (\(t.move.energy))".padding(toLength: 25, withPad: " ", startingAt: 0)
    let energy = "\(t.before) → \(t.after)".padding(toLength: 13, withPad: " ", startingAt: 0)
    out.append(String(format: "  %-2d %@  %@ %@ %@ %-11d %@%@",
                      i + 1, clock(t.time), name(t.speciesId).padding(toLength: 21, withPad: " ", startingAt: 0),
                      move, energy, count, (handCount.map { String($0) } ?? "?").padding(toLength: 4, withPad: " ", startingAt: 0), verdict))
    out.append("       calc: \(t.before) = \(prev) left before + \(count) × \(gain) (\(t.fast?.name ?? "?"))\(t.before - prev - count * gain != 0 ? " + \(t.before - prev - count * gain) (capped/partial)" : ""); after: \(t.before) − \(t.move.energy) = \(t.after)")
    if let note = hand?.notes?[String(i + 1)] { out.append("       note: \(note)") }
}
out.append("")
out.append("SUMMARY")
out.append("  \(matches) of \(checked) hand-counted charged moves match ManGo's fast move count exactly.")
if throwsSeen.count > checked { out.append("  \(throwsSeen.count - checked) not hand-counted.") }
out.append("")
out.append("TIMELINE (what the screen reader saw and did)")
out.append(contentsOf: timeline.map { "  " + $0 })
print(out.joined(separator: "\n"))
